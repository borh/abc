#!/usr/bin/env bash
set -euo pipefail

: "${PARSER_RQ_LOCK:?set PARSER_RQ_LOCK}"
: "${PARSER_RQ_CANDIDATE:?set PARSER_RQ_CANDIDATE}"
: "${PARSER_RQ_AUTHORIZATION:?set PARSER_RQ_AUTHORIZATION}"
: "${PARSER_RQ_AUTHORIZATION_TIME:?set PARSER_RQ_AUTHORIZATION_TIME}"
: "${PARSER_RQ_PROVENANCE_VERIFY:?set PARSER_RQ_PROVENANCE_VERIFY}"
: "${PARSER_RQ_CORE_CAPTURE:?set PARSER_RQ_CORE_CAPTURE}"
: "${PARSER_RQ_SOURCE_CAPTURE:?set PARSER_RQ_SOURCE_CAPTURE}"
: "${PARSER_RQ_PREDICATE_CAPTURE:?set PARSER_RQ_PREDICATE_CAPTURE}"
: "${PARSER_RQ_DIAGNOSTIC_CAPTURE:?set PARSER_RQ_DIAGNOSTIC_CAPTURE}"
: "${PARSER_RQ_PUBLICATION_CAPTURE:?set PARSER_RQ_PUBLICATION_CAPTURE}"
: "${PARSER_RQ_RESOURCE_CAPTURE:?set PARSER_RQ_RESOURCE_CAPTURE}"
: "${PARSER_RQ_DERIVE_AND_COMPOSE:?set PARSER_RQ_DERIVE_AND_COMPOSE}"

exec 9>"$PARSER_RQ_LOCK"
flock -n 9

# Provenance and authorization are checked before any candidate process starts.
# There is no retry, registry edit, or output membership scan.
"$PARSER_RQ_PROVENANCE_VERIFY"
clojure -M:abc/parser-rq-campaign verify-authorization \
  "$PARSER_RQ_CANDIDATE" "$PARSER_RQ_AUTHORIZATION" "$PARSER_RQ_AUTHORIZATION_TIME"

"$PARSER_RQ_CORE_CAPTURE"
"$PARSER_RQ_SOURCE_CAPTURE"
"$PARSER_RQ_PREDICATE_CAPTURE"
"$PARSER_RQ_DIAGNOSTIC_CAPTURE"
"$PARSER_RQ_PUBLICATION_CAPTURE"
"$PARSER_RQ_RESOURCE_CAPTURE"
"$PARSER_RQ_DERIVE_AND_COMPOSE"
